const fs = require('fs');
const path = require('path');

const snapshotDir = path.join(__dirname, '..', 'backups', 'snapshot_pre_cleanup');
const outputFile = path.join(__dirname, '..', 'backups', 'restore_staging_database.sql');

function escapeSqlValue(val) {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'number') return isNaN(val) ? 'NULL' : String(val);
  if (typeof val === 'boolean') return val ? 'TRUE' : 'FALSE';
  if (typeof val === 'object') {
    // For arrays or objects, stringify and escape
    const jsonStr = JSON.stringify(val);
    return `'${jsonStr.replace(/'/g, "''")}'`;
  }
  // String: escape single quotes and normalize carriage returns
  const s = String(val).replace(/'/g, "''");
  return `'${s}'`;
}

function generateInserts(tableName, rows, batchSize = 50) {
  if (!rows || rows.length === 0) return `-- No data for ${tableName}\n`;
  
  let sql = `-- Data for ${tableName} (${rows.length} rows)\n`;
  
  // Group rows by identical keys or use uniform keys
  for (let i = 0; i < rows.length; i += batchSize) {
    const chunk = rows.slice(i, i + batchSize);
    
    // Determine the union of columns for this chunk
    const colsSet = new Set();
    chunk.forEach(r => Object.keys(r).forEach(k => colsSet.add(k)));
    const cols = Array.from(colsSet);
    
    const colsHeader = cols.map(c => `"${c}"`).join(', ');
    sql += `INSERT INTO public.${tableName} (${colsHeader}) VALUES\n`;
    
    const valueLines = chunk.map((r, rowIdx) => {
      const vals = cols.map(c => escapeSqlValue(r[c]));
      const isLast = (rowIdx === chunk.length - 1);
      return `(${vals.join(', ')})${isLast ? '' : ','}`;
    });
    
    sql += valueLines.join('\n') + '\nON CONFLICT DO NOTHING;\n\n';
  }
  
  return sql;
}

